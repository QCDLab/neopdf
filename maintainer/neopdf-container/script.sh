#!/bin/bash

set -euo pipefail

pkgs=(
    build-essential
    curl
    gfortran
    git
    libssl-dev
    openssl
    pkg-config
    python3
    python3-dev
    python3-pip
    python3-venv
    autoconf
    automake
    libtool
    cython3
    wget
    libgsl-dev
    texlive-latex-base
    texlive-latex-extra
    texlive-pictures
    texlive-fonts-recommended
)

pdf_sets=(
    NNPDF40_nnlo_as_01180
    MSHT20qed_an3lo
    CT18NNLO_as_0118
    NNPDF40_nnlo_as_01160
    NNPDF40_an3lo_as_01180_qed_mhou
    EPPS21nlo_CT18Anlo_Fe56
    MAPFF10NLOPIsum
    NNPDFpol20_nnlo_as_01180
    nNNPDF30_nlo_as_0118_A56_Z26
    ABMP16_5_nnlo
    ABMP16als118_5_nnlo
    MSHT20nlo_as_smallrange_nf4
)

neopdf_sets=(
    NNPDF40_nnlo_as_01180
    MAP22_grids_FF_Km_N3LL
)

apt update
apt install -y "${pkgs[@]}"

# link cython to cython3
ln -s /usr/bin/cython3 /usr/local/bin/cython

# install rustup
curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- --default-toolchain none -y

for version in ${RUST_V}; do
    # the last command will be the default
    rustup install "${version}" --profile minimal
    rustup default "${version}"
    # install LLVM tools needed for code coverage
    rustup component add llvm-tools
done

# install cargo-c needed for the CAPI
cargo install --locked cargo-c --version "${CARGOC_V}"

# remove files generated by cargo
rm -r /usr/local/cargo/registry

# ==== install LHAPDF ====
curl -L "https://lhapdf.hepforge.org/downloads/?f=LHAPDF-${LHAPDF_V}.tar.gz" | tar xzf -
cd "LHAPDF-${LHAPDF_V}"
autoreconf -f -i
PYTHON=$(which python3) ./configure --prefix=/usr --enable-python
touch wrappers/python/lhapdf.pyx
make -j V=1
make install
ldconfig
# Verify the Python module was installed
bash -c "lhapdf-config --datadir"
python3 -c "import sys; print(sys.path)"
python3 -c "import lhapdf; print('LHAPDF imported successfully')"
cd ..

# ==== install TMDlib ====
# configure requires an explicit LHAPDF prefix; without it the build errors
# on an empty ${LHAPDF_DIR}. It only looks in $prefix/lib and $prefix/lib64.
if ! ls /usr/lib/libLHAPDF.* >/dev/null 2>&1 && ! ls /usr/lib64/libLHAPDF.* >/dev/null 2>&1; then
    lhapdf_lib=$(find /usr -name 'libLHAPDF.so' -print -quit || true)
    if [ -z "${lhapdf_lib}" ]; then
        echo "LHAPDF libraries were not installed under /usr" >&2
        exit 1
    fi
    ln -s "$(dirname "${lhapdf_lib}")"/libLHAPDF.* /usr/lib/
fi
curl -L "https://tmdlib.hepforge.org/downloads/?f=tmdlib-${TMDLIB_V}.tar.gz" | tar xzf -
cd "tmdlib-${TMDLIB_V}"
./configure --prefix=/usr --with-lhapdf=/usr
make -j V=1
make install
cd ..
ldconfig
TMDlib-config --version
TMDlib-config --libdir
TMDlib-config --ldflags
test -e "$(TMDlib-config --libdir)/libTMDlib.so"
test -e "$(TMDlib-config --libdir)/libapfelxx.so"

# install PDF sets
for pdf in "${pdf_sets[@]}"; do
    # see the following link why `--no-same-owner` may be necessary:
    # https://github.com/habitat-sh/builder/issues/365#issuecomment-382862233
    curl "https://lhapdfsets.web.cern.ch/current/${pdf}.tar.gz" | tar xzf - --no-same-owner -C /usr/share/LHAPDF
done

# Download NeoPDF sets
for neo in "${neopdf_sets[@]}"; do
    wget --no-verbose --no-clobber -P /usr/share/LHAPDF "https://data.nnpdf.science/neopdf/data/${neo}.neopdf.lz4"
done
